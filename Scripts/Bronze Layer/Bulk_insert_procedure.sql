==========================================================================================================================================================================================
🥉 Bronze Layer — Automated Data Loading Procedure
==========================================================================================================================================================================================
📌 Overview

- This SQL script implements the Bronze Layer data-loading process of the Data Warehouse.
- The purpose of this stored procedure is to automate the movement of raw data from external CRM and ERP CSV source files into their corresponding tables within the bronze schema.
- Instead of manually executing multiple BULK INSERT statements every time the source data needs to be refreshed, the complete ingestion process is encapsulated inside a reusable stored procedure:
bronze.load_bronze
- The procedure follows a Full Load approach. Before loading new data, each Bronze table is truncated to remove the previous dataset. The latest CSV files are then loaded into the empty tables using BULK INSERT.
- The procedure also records the processing time for each individual table and the total batch duration. TRY...CATCH error handling is included so that any failure during the loading process can be identified through the corresponding SQL Server error information.
==========================================================================================================================================================================================

🎯 Process Objective

The main objective of this procedure is to create a repeatable and automated Bronze-layer ingestion process ,the overall process is:

CRM / ERP CSV Files
        │
        ▼
Bronze Stored Procedure
        │
        ▼
Truncate Existing Tables
        │
        ▼
Bulk Insert Latest Source Data
        │
        ▼
Bronze Tables
        │
        ▼
Processing Time & Status Logging

============================================================================================================================
